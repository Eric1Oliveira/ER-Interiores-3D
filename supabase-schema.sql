-- 1. TABELA DE USUÁRIOS
CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email character varying NOT NULL UNIQUE,
  password character varying NOT NULL,
  name character varying NOT NULL,
  role character varying NOT NULL DEFAULT 'client'
    CHECK (role IN ('admin', 'employee', 'client')),
  created_at timestamp with time zone DEFAULT now()
);

-- 2. TABELA DE CATÁLOGOS
CREATE TABLE public.catalogs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name character varying NOT NULL,
  description text,
  specialty character varying,
  experience character varying,
  city character varying,
  image character varying,
  rating numeric DEFAULT 5.0,
  projects integer DEFAULT 0,
  tags text[] DEFAULT '{}',
  created_at timestamp with time zone DEFAULT now()
);

-- 3. TABELA DE CHATS
CREATE TABLE public.chats (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  catalog_id bigint NOT NULL REFERENCES public.catalogs(id) ON DELETE CASCADE,
  status character varying NOT NULL DEFAULT 'pending'
    CHECK (status IN ('active', 'pending', 'closed')),
  last_message text,
  last_message_time timestamp with time zone DEFAULT now(),
  unread integer DEFAULT 0,
  created_at timestamp with time zone DEFAULT now()
);

-- 4. TABELA DE MENSAGENS
CREATE TABLE public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id bigint NOT NULL REFERENCES public.chats(id) ON DELETE CASCADE,
  sender_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  content text NOT NULL,
  created_at timestamp with time zone DEFAULT now()
);

-- 5. TABELA DE PROJETOS
CREATE TABLE public.projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  catalog_id bigint NOT NULL REFERENCES public.catalogs(id) ON DELETE CASCADE,
  title character varying NOT NULL,
  status character varying NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'completed')),
  value numeric,
  created_at timestamp with time zone DEFAULT now()
);

-- =============================================
-- ÍNDICES PARA PERFORMANCE
-- =============================================
CREATE INDEX idx_chats_client_id ON public.chats(client_id);
CREATE INDEX idx_chats_catalog_id ON public.chats(catalog_id);
CREATE INDEX idx_messages_chat_id ON public.messages(chat_id);
CREATE INDEX idx_messages_created_at ON public.messages(created_at);
CREATE INDEX idx_projects_client_id ON public.projects(client_id);
CREATE INDEX idx_projects_catalog_id ON public.projects(catalog_id);
CREATE INDEX idx_users_email ON public.users(email);
CREATE INDEX idx_users_role ON public.users(role);

