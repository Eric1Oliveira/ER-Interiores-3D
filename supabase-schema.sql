-- =============================================
-- VIEW: chats com nomes do cliente e catálogo
-- =============================================
CREATE OR REPLACE VIEW public.chats_with_names AS
SELECT
  c.*,
  u.name AS client_name,
  cat.name AS catalog_name
FROM public.chats c
JOIN public.users u ON u.id = c.client_id
JOIN public.catalogs cat ON cat.id = c.catalog_id;

-- =============================================
-- VIEW: mensagens com dados do remetente
-- =============================================
CREATE OR REPLACE VIEW public.messages_with_sender AS
SELECT
  m.*,
  u.name AS sender_name,
  u.role AS sender_role
FROM public.messages m
JOIN public.users u ON u.id = m.sender_id;

-- =============================================
-- VIEW: projetos com nomes
-- =============================================
CREATE OR REPLACE VIEW public.projects_with_names AS
SELECT
  p.*,
  u.name AS client_name,
  cat.name AS catalog_name
FROM public.projects p
JOIN public.users u ON u.id = p.client_id
JOIN public.catalogs cat ON cat.id = p.catalog_id;

-- =============================================
-- FUNÇÃO: atualizar last_message do chat
-- =============================================
CREATE OR REPLACE FUNCTION public.update_chat_last_message()
RETURNS TRIGGER AS $$
BEGIN
  UPDATE public.chats
  SET last_message = NEW.content,
      last_message_time = NEW.created_at
  WHERE id = NEW.chat_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_new_message
  AFTER INSERT ON public.messages
  FOR EACH ROW
  EXECUTE FUNCTION public.update_chat_last_message();

